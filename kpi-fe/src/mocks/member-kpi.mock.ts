export function getMockMemberKpiDashboard(year = 2025): MemberKpiDashboard {
  const operationalItems = KPI_ITEMS
  const promotionItems = MOCK_PROMOTION_KPI_ITEMS
  const sheetItems = [...operationalItems, ...promotionItems]

  const totalWeight = operationalItems.reduce((s, i) => s + i.weight, 0)
  const evidenceSubmitted = operationalItems.filter(i => i.evidenceStatus === 'submitted').length

  return {
    year,
    phase: 'year_end',
    phaseLabel: 'Giai đoạn Cuối Năm',
    sheet: {
      id: 'sheet-member-1',
      userId: 'u-member-1',
      userName: 'Trần Văn Phước',
      rank: 'R3',
      year,
      phase: 'year_end',
      items: sheetItems,
      totalWeight,
      evidenceCount: evidenceSubmitted,
      evidenceTotalCount: operationalItems.length,
      status: 'draft',
    },
    pendingItems: ['A.2a', 'B.1', 'B.2'],
    canSubmit: false,
  }
}
